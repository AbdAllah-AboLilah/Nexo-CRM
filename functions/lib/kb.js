/** تحويل الدليل لنص يتحط في تعليمات الذكاء الاصطناعي */
function buildKnowledgeText(features = {}) {
  return ARTICLES.map((a) => {
    const available = !a.feature || features[a.feature] === true;
    const lines = [`### ${a.topic}`, `الحالة عند الشركة دي: ${available ? "متاحة ✅" : "مش متاحة في باقتها ❌"}`];
    if (a.minRole) lines.push(`أقل صلاحية مطلوبة: ${a.minRole}`);
    if (a.steps?.length) lines.push("الخطوات:", ...a.steps.map((s, i) => `${i + 1}. ${s}`));
    if (a.notes?.length) lines.push("ملاحظات:", ...a.notes.map((n) => `- ${n}`));
    return lines.join("\n");
  }).join("\n\n");
}

module.exports = { ARTICLES, buildKnowledgeText };
